// Temporada 2: «Las profundidades». Debajo del templo hay cuevas, y los niveles van por mundos.
// Cada nivel tiene el mismo formato que los de levels.js (ver allí la leyenda completa) y se
// puede dibujar con el editor. Casillas que estrena esta temporada:
//   ⚑      bandera de control: se enciende cuando los tres están junto a ella. Si después
//          alguien cae (o se pulsa R), todo vuelve a como estaba al encenderla, con las vidas llenas.
//   ≈ ♨    barril de agua / de lava: se empuja como una caja. Al llegar a un charco del elemento
//          contrario (agua sobre lava, lava sobre agua) lo convierte entero en obsidiana y se gasta
//   ■      obsidiana: suelo para todos (la forman los barriles; también se puede dibujar)
//   Ω      el Gólem de magma (jefe del Mundo 1): anda por el suelo entre las columnas golem.left y
//          golem.right, lanza brasas y da pisotones. Solo le hace daño un barril de agua que le toque
//          (aguanta 4); al caer se rompen los sellos / del nivel
//   ▼      dispensador: suelta un barril de agua, y otro al rato cada vez que el suyo se gasta
//
// Marea (Mundo 2): con "tide" en el nivel, un líquido sube desde el suelo; solo aguanta dentro
// el personaje de su elemento (los demás se hunden si les cubre la cabeza).
//   tide: { type: "water" | "fire" | "acid", delay: frames antes de empezar, speed: píxeles por
//           frame, top: fila más alta a la que llega, start: filas por encima del suelo al empezar }
//   Un mecanismo con kind: "drain" (desagüe) solo lleva botón o palanca: mientras está activo, la
//   marea baja. Un barril del elemento contrario que se hunde en ella la hace bajar 3 casillas.
//   Las cajas flotan en la marea y suben con ella, llevando a quien va encima (los barriles no).
//   Ψ      la Hidra del aljibe (jefe del Mundo 2): necesita marea y un desagüe. En cada fase la marea
//          es de un elemento (agua, lava, ácido); vaciarla con un desagüe después de que haya llegado
//          arriba le quita una cabeza. Al perder las tres se rompen los sellos /
//
// Oscuridad (Mundo 3): con "dark: true" en el nivel solo se ve lo que da luz: Chispa (mucha),
// Gota y Acidito (un poco, a su alrededor), antorchas encendidas, faroles, lava, ácido (poco),
// gemas, puertas, portales y fantasmas. El agua no brilla.
//   †      antorcha apagada: la enciende Chispa al tocarla o una bola de fuego
//   ‡      antorcha ya encendida
//   ¤      farol: quien lo agarra lleva luz consigo (uno por personaje)
//   La marea de agua apaga las antorchas que cubre; la de lava las enciende.
//   ☾      la Sombra de la mina (jefe del Mundo 3): flota hacia Gota o Acidito atravesando paredes;
//          si se queda un rato a la luz de una antorcha encendida se quema (aguanta 5), apaga esa
//          antorcha y huye. Cada cierto tiempo apaga otra. Al caer se rompen los sellos /
//
// Géiseres (Mundo 4): respiraderos en la fila del suelo (son suelo para todos) que cada poco lanzan
// un chorro de su líquido hasta 6 casillas de alto (o hasta el primer obstáculo). Al personaje de su
// elemento lo suben como un ventilador; a los demás los matan. Burbujean un segundo antes de salir.
//   ↥ ↟ ⇞  géiser de lava, de agua y de ácido
//   Una caja encima del respiradero lo tapa mientras esté ahí. Un barril del elemento contrario
//   (agua sobre lava, lava sobre agua) lo sella con obsidiana para siempre.
//   geyser: { calm: frames tranquilo, burst: frames del chorro, stagger: retraso entre un géiser y
//             el siguiente (en orden de lectura), steady: "fire" | ["water", …] los que no paran nunca }
//
//   Ж      el Cangrejo hirviente (jefe del Mundo 4): necesita géiseres de los tres elementos. Persigue
//          por el suelo al que tenga más cerca y abre las tenazas para pellizcar; a veces salta y
//          hace ondas. Solo le duele el chorro del géiser de un elemento, que cambia por fases (agua,
//          lava, ácido; dos golpes cada una). crab: { name, left, right } (columnas por las que anda).
//          Al caer se rompen los sellos /
//
// Estrellas de cada nivel: completarlo, recoger todas sus gemas y pasarlo sin perder un corazón
// (ni volver a una bandera). Se pueden ganar en partidas distintas.
//
// Las casillas nuevas son símbolos de un solo carácter (como ⚑), nunca emojis: un emoji ocupa
// dos caracteres y descuadra las filas del mapa.

